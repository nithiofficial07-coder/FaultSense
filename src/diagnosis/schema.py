"""Domain models and schemas for structured, evidence-grounded diagnostic reports.

Provides validated dataclasses representing ranked root-cause hypotheses,
traceable supporting/conflicting evidence, recommended diagnostic checks,
corrective actions, and uncertainty analysis.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional


class DiagnosticStatus(str, Enum):
    """Execution status of the root cause analysis session."""
    COMPLETED = "completed"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    INCONCLUSIVE = "inconclusive"
    REJECTED_UNSUPPORTED = "rejected_unsupported"
    FALLBACK_DETERMINISTIC = "fallback_deterministic"
    FAILED = "failed"


class ProbabilityBand(str, Enum):
    """Categorical likelihood band for a candidate cause (never calibrated probability)."""
    LIKELY = "likely"
    POSSIBLE = "possible"
    UNLIKELY = "unlikely"


@dataclass
class CandidateCause:
    """A single hypothesized root cause supported by historical evidence."""
    rank: int
    hypothesis_title: str
    subsystem: str
    probability_band: str  # likely, possible, unlikely
    explanation: str
    supporting_case_ids: List[str] = field(default_factory=list)
    conflicting_evidence: List[str] = field(default_factory=list)
    recommended_checks: List[str] = field(default_factory=list)
    documented_corrective_actions: List[str] = field(default_factory=list)
    citation_warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class DiagnosticReport:
    """Comprehensive diagnostic investigation report generated by LLM reasoning or deterministic fallback."""
    investigation_id: str
    elevator_id: str
    subsystem: str
    fault_code: Optional[str]
    status: str  # DiagnosticStatus
    summary: str
    candidate_causes: List[CandidateCause]
    uncertainty_and_missing_info: List[str] = field(default_factory=list)
    safety_advisories: List[str] = field(default_factory=list)
    retrieved_case_ids: List[str] = field(default_factory=list)
    generation_mode: str = "fallback_deterministic"  # "llm_reasoning", "fallback_deterministic", "mock_test"
    model_metadata: Dict[str, Any] = field(default_factory=dict)
    confidence_score: float = 0.50
    verification_verdict: Optional[str] = None  # "sufficient", "insufficient", "inconclusive", "contradicted"
    verification_details: Optional[Dict[str, Any]] = None
    retry_count: int = 0
    disclaimer: str = (
        "Diagnostic Decision Support Notice: Generated root cause hypotheses, confidence scores, and "
        "recommended actions are advisory. Confidence scores do NOT represent calibrated statistical "
        "probabilities of failure. Technicians must strictly adhere to physical lock-out/tag-out (LOTO) "
        "procedures, OEM schematics, and on-site multimeter measurements before servicing equipment."
    )
    timestamp: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    @property
    def is_fallback(self) -> bool:
        return self.generation_mode == "fallback_deterministic"

    @property
    def top_candidate(self) -> Optional[CandidateCause]:
        return self.candidate_causes[0] if self.candidate_causes else None

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["candidate_causes"] = [c.to_dict() for c in self.candidate_causes]
        return d

    def summary_markdown(self) -> str:
        """Renders formatted Markdown for Streamlit UI or terminal reports."""
        status_line = f"**Status**: `{self.status.upper()}` | **Generation Mode**: `{self.generation_mode}`"
        if self.verification_verdict:
            status_line += f" | **Verification**: `{self.verification_verdict.upper()}` (Retries: {self.retry_count})"

        lines = [
            f"### 📋 Diagnostic Report: {self.investigation_id}",
            f"**Elevator Unit**: `{self.elevator_id}` | **Subsystem**: `{self.subsystem}` | **Fault Code**: `{self.fault_code or 'None'}`",
            status_line,
            f"**Confidence Assessment**: `{int(self.confidence_score * 100)}%` (Advisory Likelihood)\n",
            f"#### 🔍 Executive Summary",
            f"{self.summary}\n",
        ]

        if self.safety_advisories:
            lines.append("#### ⚠️ Mandatory Safety Advisories")
            for adv in self.safety_advisories:
                lines.append(f"- **SAFETY**: {adv}")
            lines.append("")

        lines.append("#### 🎯 Ranked Candidate Root Causes")
        if not self.candidate_causes:
            lines.append("_No candidate root causes identified from available evidence._\n")
        else:
            for c in self.candidate_causes:
                cites = ", ".join(f"`{cid}`" for cid in c.supporting_case_ids) if c.supporting_case_ids else "None"
                lines.append(f"**#{c.rank}. {c.hypothesis_title}** [{c.subsystem.upper()} — Band: *{c.probability_band.upper()}*]")
                lines.append(f"- **Explanation**: {c.explanation}")
                lines.append(f"- **Supporting Evidence (Citations)**: {cites}")
                if c.conflicting_evidence:
                    lines.append(f"- **Conflicting Evidence**: {'; '.join(c.conflicting_evidence)}")
                if c.recommended_checks:
                    lines.append(f"- **Next Diagnostic Checks**: {'; '.join(c.recommended_checks)}")
                if c.documented_corrective_actions:
                    lines.append(f"- **Documented Corrective Actions**: {'; '.join(c.documented_corrective_actions)}")
                if c.citation_warnings:
                    for cw in c.citation_warnings:
                        lines.append(f"- ⚠️ *Citation Warning*: {cw}")
                lines.append("")

        if self.uncertainty_and_missing_info:
            lines.append("#### ❓ Uncertainty & Missing Information")
            for u in self.uncertainty_and_missing_info:
                lines.append(f"- {u}")
            lines.append("")

        lines.append(f"> ℹ️ _{self.disclaimer}_")
        return "\n".join(lines)
